export const FONT_HEIGHT = 9;
export const FONT_BASELINE = 6;

/** Parse the glyph table into [charCode, rows[]] pairs. */
function parseTable(src) {
  const lines = src
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l.length > 0);
  if (lines.length % 10) throw new Error('font: table must be blocks of 10 lines');
  const out = [];
  for (let i = 0; i < lines.length; i += 10) {
    const head = lines[i].split(/\s+/);
    const rows = lines.slice(i + 1, i + 10).map((l) => l.split(/\s+/));
    rows.forEach((r, y) => {
      if (r.length !== head.length) throw new Error(`font: block '${lines[i]}' row ${y} has ${r.length} tokens`);
    });
    head.forEach((tok, k) => {
      const code = tok.length === 1 ? tok.charCodeAt(0) : Number(tok);
      const glyph = rows.map((r) => r[k]);
      const w = glyph[0].length;
      if (glyph.some((g) => g.length !== w)) throw new Error(`font: glyph ${tok} has ragged rows`);
      out.push([code, glyph]);
    });
  }
  return out;
}

export function register(A) {
  A.pal('font', ['#181010']);
  A.pal('font_light', ['#f8f8e8']);
  A.pal('font_dim', ['#788080']);
  A.pal('font_gold', ['#f8c030']);
  A.pal('font_red', ['#d83828']);
  A.pal('font_blue', ['#3060c8']);

  // Space: 3 px of nothing.
  A.sprite('font_32', 'font', Array(9).fill('...').join('\n'));

  const seen = new Set([32]);
  for (const [code, rows] of parseTable(TABLE)) {
    if (seen.has(code)) throw new Error(`font: duplicate glyph ${code}`);
    seen.add(code);
    A.sprite(`font_${code}`, 'font', rows.map((r) => r.replace(/#/g, '1')).join('\n'));
  }
  for (let c = 32; c <= 126; c++) if (!seen.has(c)) throw new Error(`font: missing glyph ${c} '${String.fromCharCode(c)}'`);
  for (let c = 128; c <= 137; c++) if (!seen.has(c)) throw new Error(`font: missing glyph ${c}`);
}
