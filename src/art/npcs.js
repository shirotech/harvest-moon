// Art module: villager NPCs (16x16, walk frames only).
// Frames: npc_<id>_<down|up|side>_<0|1>. See docs/ART_GUIDE.md.
//
// Each villager gives full 16-row art for the standing frames (down0/up0/side0).
// The mid-step frames (down1/up1/side1) are [firstRow, art]: the standing frame
// with the rows from `firstRow` down replaced (legs, arms, skirt hem).
// Adults: head in rows 0-8, feet in rows 14-15. Pip, the kid, starts at row 3.

function rows(art, name) {
  const r = art
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l.length);
  r.forEach((l, i) => {
    if (l.length !== 16) throw new Error(`${name}: row ${i} has width ${l.length}`);
  });
  return r;
}

/** Replace rows of `base` starting at `from` with the rows of `art`. */
function patch(base, from, art, name) {
  const out = base.slice();
  rows(art, name).forEach((l, i) => (out[from + i] = l));
  return out;
}

function npc(A, id, colors, f) {
  const pal = A.pal(`npc_${id}`, colors);
  const d0 = rows(f.down0, id), u0 = rows(f.up0, id), s0 = rows(f.side0, id);
  const frames = {
    down_0: d0,
    down_1: patch(d0, f.down1[0], f.down1[1], id),
    up_0: u0,
    up_1: patch(u0, f.up1[0], f.up1[1], id),
    side_0: s0,
    side_1: patch(s0, f.side1[0], f.side1[1], id),
  };
  for (const [k, r] of Object.entries(frames)) {
    if (r.length !== 16) throw new Error(`npc_${id}_${k}: ${r.length} rows`);
    A.sprite(`npc_${id}_${k}`, pal, r.join('\n'));
  }
}

