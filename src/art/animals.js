// Art module: animals. See docs/ART_GUIDE.md for the sprite contract.
//
// Farm animals and ambient critters. Side frames face right (the engine
// mirrors them for left). Frame 0 = standing, frame 1 = mid-step.

/** Strict ASCII sprite: every row must have exactly `w` columns and `h` rows. */
function art(A, name, pal, w, h, src) {
  const rows = src
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean);
  if (rows.length !== h) throw new Error(`${name}: expected ${h} rows, got ${rows.length}`);
  rows.forEach((r, i) => {
    if (r.length !== w) throw new Error(`${name}: row ${i} is ${r.length} wide, expected ${w}`);
  });
  A.sprite(name, pal, rows.join('\n'));
}

