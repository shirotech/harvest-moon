// Shared index layout: 1 outline, 2 wood dark, 3 wood light,
// 4 metal dark, 5 metal mid, 6 metal highlight. The grip is at ~(2,13).

function tools(A) {
  const WOOD = ['#603820', '#a06838'];
  A.pal('tool', [O, ...WOOD, '#485060', '#8890a0', '#d8e0e8']);
  A.pal('tool_copper', [O, ...WOOD, '#903018', '#d86840', '#f8b890']);
  A.pal('tool_gold', [O, ...WOOD, '#a06808', '#e8b830', '#f8f0a0']);

  // wooden handle along x+y = 15 (light) / 16 (dark), from x0 to x1
  const handle = (g, x0, x1) => {
    for (let x = x0; x <= x1; x++) {
      g.px(x, 15 - x, 3);
      g.px(x + 1, 15 - x, 2);
    }
  };

  A.paint('tool_hoe', 'tool', 16, 16, (g) => {
    handle(g, 2, 10);
    draw(g, 10, 2, `
      4555.
      45666
      .4566
      ..466
      ..466
      ..466
      ..456
      ...45
    `);
    outline(g);
  });

  A.paint('tool_can', 'tool', 16, 16, (g) => {
    draw(g, 0, 0, `
      ................
      ................
      ................
      ............666.
      ............565.
      .............5..
      ....44444....5..
      ..56666666...5..
      .5.6555554..5...
      .5.6555554.5....
      .5.65555545.....
      .5.6555554......
      ..55555544......
      ...4444444......
      ................
      ................
    `);
    outline(g);
  });

  A.paint('tool_sickle', 'tool', 16, 16, (g) => {
    draw(g, 1, 1, `
      .......555....
      .....5566655..
      ....566....65.
      ...56.......6.
      ...56.........
      ...56.........
      ...45.........
      ...4..........
      ..32..........
      ..32..........
      .32...........
      .32...........
      32............
    `);
    outline(g);
  });

  A.paint('tool_hammer', 'tool', 16, 16, (g) => {
    handle(g, 2, 9);
    for (let y = 0; y < 16; y++)
      for (let x = 0; x < 16; x++) {
        const s = x + y, d = x - y;
        if (d < 4 || d > 8 || s < 10 || s > 21) continue;
        let c = 5;
        if (d === 8) c = 6;
        else if (d === 4) c = 4;
        if (s >= 20) c = 4;
        if (s <= 11) c = 6;
        g.px(x, y, c);
      }
    outline(g);
  });

  A.paint('tool_axe', 'tool', 16, 16, (g) => {
    handle(g, 2, 11);
    for (let y = 0; y < 16; y++)
      for (let x = 0; x < 16; x++) {
        const s = x + y, d = x - y;
        if (s < 16 || s > 23) continue;
        if (x > 14 || y < 1) continue;
        const spread = s - 16;
        const lo = 5 - Math.floor(spread / 2), hi = 8 + Math.floor(spread / 3);
        if (d < lo || d > hi) continue;
        let c = 5;
        if (s >= 22) c = 6;
        else if (d === lo) c = 4;
        else if (d === hi) c = 6;
        g.px(x, y, c);
      }
    outline(g);
  });

  A.paint('tool_rod', 'tool', 16, 16, (g) => {
    for (let x = 5; x <= 14; x++) g.px(x, 15 - x, 3);
    handle(g, 1, 4);
    draw(g, 4, 9, `
      45.
      566
      .5.
    `);
    outline(g);
    for (let y = 2; y <= 9; y++) g.px(14, y, 4);
    g.px(14, 10, 5);
  });

  // hand milker: wooden grip, banded metal tube, flared teat cup
  A.paint('tool_milker', 'tool', 16, 16, (g) => {
    handle(g, 2, 5);
    for (let y = 1; y < 15; y++)
      for (let x = 1; x < 15; x++) {
        const s = x + y, d = x - y;
        if (d < -2 || d > 9) continue;
        const ds = s - 15.5;
        const w = d >= 7 ? 3 + (d - 7) : 2;
        if (Math.abs(ds) > w) continue;
        let c = 5;
        if (ds < -w + 1) c = 6;
        else if (ds > w - 1) c = 4;
        if (d === -2 || d === 1 || d === 4) c = ds < -w + 1 ? 5 : 4;
        if (d === 9) c = 4;
        g.px(x, y, c);
      }
    outline(g);
  });

  // grooming brush seen face-on: oval wooden back, bristle field in metal tones
  A.paint('tool_brush', 'tool', 16, 16, (g) => {
    handle(g, 2, 6);
    for (let y = 1; y < 15; y++)
      for (let x = 1; x < 15; x++) {
        const s = x + y, d = x - y;
        const u = (d - 5.5) / 6.4, v = (s - 15.5) / 4.1;
        if (u * u + v * v > 1) continue;
        const iu = (d - 5.5) / 4.6, iv = (s - 15.5) / 2.6;
        let c = s < 15.5 ? 3 : 2;
        if (iu * iu + iv * iv <= 1) c = (x + y) % 2 ? 4 : 6;
        g.px(x, y, c);
      }
    outline(g);
  });
}

