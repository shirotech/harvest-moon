// Art module: items. See docs/ART_GUIDE.md for the sprite contract.
//
// 16x16 inventory / held-item icons and the diagonal tools. Most icons are
// drawn as interior colours only; `item()` then wraps every coloured pixel in
// the shared #181010 outline (4-neighbour, so corners come out rounded), which
// keeps silhouettes closed and consistent. Index 1 drawn explicitly in the art
// (eyes, stems, creases) never grows an outline of its own.

const O = '#181010';

// ---------------------------------------------------------------- helpers

function grid(art) {
  const rows = art
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean);
  const w = rows[0].length;
  for (const r of rows) if (r.length !== w) throw new Error(`items: ragged art row "${r}" (${r.length} vs ${w})`);
  return rows.map((r) => [...r].map((c) => (c === '.' ? 0 : c.charCodeAt(0) - 48)));
}

const N4 = [[1, 0], [-1, 0], [0, 1], [0, -1]];
const N8 = [...N4, [1, 1], [1, -1], [-1, 1], [-1, -1]];

/** Outline every transparent pixel touching a colour > 1. */
function outline(g, diag = false) {
  const src = g.data.slice();
  const nb = diag ? N8 : N4;
  for (let y = 0; y < g.h; y++)
    for (let x = 0; x < g.w; x++) {
      if (src[y * g.w + x]) continue;
      for (const [dx, dy] of nb) {
        const xx = x + dx, yy = y + dy;
        if (xx < 0 || yy < 0 || xx >= g.w || yy >= g.h) continue;
        if (src[yy * g.w + xx] > 1) {
          g.px(x, y, 1);
          break;
        }
      }
    }
}

/** Draw art at (x0,y0) with its own outline painted over whatever is below. */
function stamp(g, x0, y0, art, diag = false) {
  const a = grid(art);
  const h = a.length, w = a[0].length;
  const at = (x, y) => (x < 0 || y < 0 || x >= w || y >= h ? 0 : a[y][x]);
  const nb = diag ? N8 : N4;
  for (let y = -1; y <= h; y++)
    for (let x = -1; x <= w; x++) {
      if (at(x, y)) continue;
      if (nb.some(([dx, dy]) => at(x + dx, y + dy) > 1)) g.px(x0 + x, y0 + y, 1);
    }
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (a[y][x]) g.px(x0 + x, y0 + y, a[y][x]);
}

/** Draw raw art (no outline). */
function draw(g, x0, y0, art) {
  const a = grid(art);
  a.forEach((row, y) => row.forEach((v, x) => v && g.px(x0 + x, y0 + y, v)));
}

/** Register an outlined icon from ASCII art. */
function item(A, name, pal, art, { diag = false, post = null } = {}) {
  const a = grid(art);
  return A.paint(name, pal, a[0].length, a.length, (g) => {
    draw(g, 0, 0, art);
    outline(g, diag);
    if (post) post(g);
  });
}

