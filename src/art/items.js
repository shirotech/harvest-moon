    A.paint(`item_seeds_${crop}`, pal, 16, 16, (g) => {
      // paper packet with a crimped top band in the crop colour
      g.rect(3, 1, 10, 14, 3);
      g.rect(3, 1, 10, 3, 4);
      g.hline(3, 12, 4, 2);
      g.vline(12, 5, 14, 2);
      g.hline(3, 12, 14, 2);
      for (let x = 3; x <= 12; x += 2) g.px(x, 1, 0);
      outline(g);
      for (let x = 4; x <= 12; x += 2) g.px(x, 0, 1);
      stamp(g, 5, 7, SEED_PICS[crop]);
    });
